LanguageOption? languageOptionForCode(String code) {
  final needle = code.trim().replaceAll('-', '_');
  for (final lang in supportedLanguages) {
    if (lang.code == needle) return lang;
  }
  final parts = needle.split('_');
  final base = parts.first;
  if (parts.length >= 2) {
    final country = parts.last.toUpperCase();
    for (final lang in supportedLanguages) {
      if (lang.flagCountry == country &&
          (lang.code == base || lang.code.startsWith('${base}_'))) {
        return lang;
      }
    }
  }
  for (final lang in supportedLanguages) {
    if (lang.code == base) return lang;
  }
  for (final lang in supportedLanguages) {
    if (lang.code.startsWith('${base}_')) return lang;
  }
  return null;
}

/// Best-effort lookup used when we detect the OS locale on first launch.
String? languageNameForCode(String code) =>
    languageOptionForCode(code)?.englishName;

/// Language list in English alphabetical order (Afrikaans…, English (UK),
/// English (USA), French (Belgium)…).
List<LanguageOption> languagesAlphabetical() {
  final list = List<LanguageOption>.from(supportedLanguages);
  list.sort((a, b) {
    final byName = a.englishName.toLowerCase().compareTo(b.englishName.toLowerCase());
    if (byName != 0) return byName;
    return a.code.compareTo(b.code);
  });
  return list;
}
