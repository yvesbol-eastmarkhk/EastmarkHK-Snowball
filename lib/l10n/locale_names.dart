/// Languages for the picker, with a country flag so the same language in
/// different countries stays distinct (Belgium vs France vs Netherlands).
///
/// Names can stay in English / native form — the AI translator handles the
/// rest of the UI. Regional codes (`fr_BE`, `nl_BE`) reuse the base-language
/// translation pack (`fr`, `nl`) when one already exists.
class LanguageOption {
  final String code;
  final String englishName;
  final String nativeName;
  final String flagCountry;

  const LanguageOption(
    this.code,
    this.englishName,
    this.nativeName, {
    required this.flagCountry,
  });
}

